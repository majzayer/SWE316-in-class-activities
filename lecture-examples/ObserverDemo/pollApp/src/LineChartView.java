public class LineChartView {
    public void drawLine(int a, int b, int c) {
        System.out.println("LineChartView:");
        System.out.println("A -> " + "-".repeat(a / 10));
        System.out.println("B -> " + "-".repeat(b / 10));
        System.out.println("C -> " + "-".repeat(c / 10));
    }
}
